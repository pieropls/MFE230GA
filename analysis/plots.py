# ---------------------------------------------------------------- Part 3: v2 windows
def v2_windows(frame, a3):
    """frame: index variant, columns = windows (Sharpe). a3: Series window -> Sharpe (confirmatory)."""
    windows = list(frame.columns)
    fig, ax = plt.subplots(figsize=(P.FULL_WIDTH, 2.8))
    n = len(frame) + 1
    width = 0.8 / n
    shades = ['#B35C00', '#D08A4A', '#E3B48A', '#F1D7BF']
    hatches = ['', '', '//', '..']
    for i, (variant, row) in enumerate(frame.iterrows()):
        x = np.arange(len(windows)) + (i - (n - 1) / 2) * width
        ax.bar(x, row.to_numpy(), width, color=shades[i], edgecolor=PH, lw=0.5, hatch=hatches[i], label=f'{variant} (post-hoc)')
    x = np.arange(len(windows)) + (n - 1 - (n - 1) / 2) * width
    values = [a3.get(w, np.nan) for w in windows]
    ax.bar(x, values, width, color=C, label='A3 primary (confirmatory)')
    for xi, v, w in zip(x, values, windows):
        if np.isnan(v):
            ax.text(xi, 0.02, 'n/a', ha='center', va='bottom', fontsize=6, color=C, rotation=90)
    ax.axhline(0, color=DGREY, lw=0.8)
    ax.set_xticks(range(len(windows)), windows)
    ax.set_ylabel('Annualised net Sharpe ratio')
    ax.set_title('v2 strategies by window, with the preregistered primary for contrast')
    ax.legend(loc='upper left', ncol=3, fontsize=7)
    ax.grid(axis='x', visible=False)
    return save(fig, 'fig_v2_windows.pdf')
