def agents_scatter(frame):
    """frame: one row per valid seed-1 candidate with study, research_ic, test_ic (NaN if undefined),
    selected (bool), gated (bool)."""
    fig, ax = plt.subplots(figsize=(P.FULL_WIDTH, 3.2))
    defined = frame.test_ic.notna()
    floor = np.nanmin(frame.test_ic) - 0.022
    for study, marker in [('Sonnet', 'o'), ('Opus', '^')]:
        for gated in [False, True]:
            sub = frame[(frame.study == study) & (frame.gated == gated)]
            y = sub.test_ic.where(sub.test_ic.notna(), floor)
            colour = PH if gated else GREY
            ax.scatter(sub.research_ic, y, marker=marker, s=22, color=colour, alpha=0.85, lw=0,
                       label=f'{study}, {"regime-gated" if gated else "ungated"}')
        sel = frame[(frame.study == study) & frame.selected]
        ax.scatter(sel.research_ic, sel.test_ic.where(sel.test_ic.notna(), floor), marker=marker, s=80,
                   facecolors='none', edgecolors='black', lw=1.0)
    ax.scatter([], [], marker='o', s=80, facecolors='none', edgecolors='black', label='selected for A3/A4')
    ax.axhline(0, color=DGREY, lw=0.7)
    ax.axvline(0, color=DGREY, lw=0.7)
    ax.axhline(floor + 0.011, color=GREY, lw=0.6, ls=':')
    ax.text(ax.get_xlim()[1], floor, 'test IC undefined\n(active ≤ 3 months)', ha='right', va='center', fontsize=6.8, color=DGREY)
