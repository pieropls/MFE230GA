# ---------------------------------------------------------------- D4 cumulative
def cumulative(confirmatory, posthoc):
    """confirmatory/posthoc: dict label -> monthly net excess return Series (test period).
    Primary 'A3' is drawn bold in the confirmatory colour; other confirmatory lines in greys."""
    fig, ax = plt.subplots(figsize=(P.FULL_WIDTH, 2.9))
    greys = iter([GREY, LGREY, DGREY, '#A6A6A6'])
    styles = iter(['-', '-', '-.', ':'])
    for label, r in confirmatory.items():
        index = (1 + r).cumprod()
        x = r.index.to_timestamp()
        if label.startswith('A3'):
            ax.plot(x, index, color=C, lw=2.0, label=label, zorder=5)
        else:
            ax.plot(x, index, color=next(greys), lw=1.1, ls=next(styles), label=label)
    for label, (r, style) in posthoc.items():
        ax.plot(r.index.to_timestamp(), (1 + r).cumprod(), color=PH, lw=1.5, ls=style, label=label, zorder=4)
    ax.axhline(1, color=DGREY, lw=0.7)
    ax.set_ylabel('Growth of $1 (net excess return)')
    ax.set_title('Test period, Nov 2014–Aug 2026: every preregistered strategy lost money')
    ax.legend(loc='lower left', ncol=2)
    ax.grid(axis='x', visible=False)
    return save(fig, 'fig_cumulative.pdf')


