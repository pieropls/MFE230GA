# ---------------------------------------------------------------- tables
def _tex(value):
    text = str(value)
    for a, b in [('\\', r'\textbackslash{}'), ('&', r'\&'), ('%', r'\%'), ('_', r'\_'), ('#', r'\#'),
                 ('−', '$-$'), ('±', r'$\pm$'), ('≥', r'$\geq$'), ('≤', r'$\leq$'), ('×', r'$\times$')]:
        text = text.replace(a, b)
    return text


def markdown(df, index=True, floatfmt='{:.4g}'):
    """Plain markdown table (no extra dependency)."""
    shown = df.reset_index() if index else df
    cell = lambda v: floatfmt.format(v) if isinstance(v, (float, np.floating)) and not np.isnan(v) else ('' if v is None or (isinstance(v, float) and np.isnan(v)) else str(v))
    rows = ['| ' + ' | '.join(map(str, shown.columns)) + ' |', '|' + '---|' * shown.shape[1]]
    rows += ['| ' + ' | '.join(cell(v) for v in row) + ' |' for row in shown.itertuples(index=False)]
    return '\n'.join(rows)


def write_table(df, name, fmt=None, index=True, align=None, label=None):
    """CSV to analysis/output/tables/<name>.csv; booktabs tabular fragment to report/tables/<name>.tex.
    `fmt` maps column -> format string (e.g. '{:+.3f}'); `label` is written as a LaTeX comment."""
    P.TABLES.mkdir(parents=True, exist_ok=True)
    P.TEX.mkdir(parents=True, exist_ok=True)
    df.to_csv(P.TABLES / f'{name}.csv', index=index)
    shown = df.reset_index() if index else df.copy()
    fmt = fmt or {}
    for col in shown.columns:
        f = fmt.get(col)
        shown[col] = [('' if (isinstance(v, float) and np.isnan(v)) or v is None else
                       (f.format(v) if f and isinstance(v, (int, float, np.integer, np.floating)) else v))
                      for v in shown[col]]
    align = align or ('l' + 'r' * (shown.shape[1] - 1))
    lines = [f'% {label or name} | source: analysis/output/tables/{name}.csv (generated by analysis/run.ipynb)',
             rf'\begin{{tabular}}{{{align}}}', r'\toprule',
             ' & '.join(_tex(c) for c in shown.columns) + r' \\', r'\midrule']
    lines += [' & '.join(_tex(v) for v in row) + r' \\' for row in shown.itertuples(index=False)]
    lines += [r'\bottomrule', r'\end{tabular}']
    (P.TEX / f'{name}.tex').write_text('\n'.join(lines) + '\n')
    return P.TEX / f'{name}.tex'


# ---------------------------------------------------------------- D1 single-signal IC
def ic_signals(table):
    """table: index signal, columns mean/se for 'research' and 'test'."""
    order = list(table.index)[::-1]
    fig, ax = plt.subplots(figsize=(P.FULL_WIDTH, 3.0))
    y = np.arange(len(order))
    for offset, period, colour, marker in [(0.17, 'research', GREY, 'o'), (-0.17, 'test', PH, 's')]:
        m = table.loc[order, f'{period}_ic'].to_numpy()
        e = 2 * table.loc[order, f'{period}_se'].to_numpy()
        ax.errorbar(m, y + offset, xerr=e, fmt=marker, color=colour, ms=4.5, capsize=2, lw=1,
                    label={'research': 'Research 2004–2014', 'test': 'Test 2014–2026'}[period])
    ax.axvline(0, color=DGREY, lw=0.8)
    ax.set_yticks(y, [SIGNAL_LABELS.get(s, s) for s in order])
    ax.set_xlabel('Mean monthly rank IC with next-month relative return (±2 s.e., Newey–West)')
    ax.set_title('Single-signal predictive power: research vs test')
    ax.legend(loc='lower right', ncol=2)
    ax.grid(axis='y', visible=False)
    return save(fig, 'fig_ic_signals.pdf')


# ---------------------------------------------------------------- D2 horizon heatmap
def horizon(ic, t):
    """ic, t: DataFrames signal x horizon."""
    fig, ax = plt.subplots(figsize=(P.HALF_WIDTH + 0.6, 3.1))
    limit = np.nanmax(np.abs(ic.to_numpy()))
    image = ax.imshow(ic.to_numpy(), cmap='RdBu_r', vmin=-limit, vmax=limit, aspect='auto')
    for i in range(ic.shape[0]):
        for j in range(ic.shape[1]):
            v, tv = ic.iat[i, j], t.iat[i, j]
            strong = abs(v) > 0.6 * limit
            ax.text(j, i, f'{v:+.3f}\n({tv:+.1f})', ha='center', va='center', fontsize=6.8,
                    color='white' if strong else 'black', fontweight='bold' if abs(tv) >= 2 else 'normal')
    ax.set_xticks(range(ic.shape[1]), [f'{h}m' for h in ic.columns])
    ax.set_yticks(range(ic.shape[0]), [SIGNAL_LABELS.get(s, s) for s in ic.index])
    ax.set_xlabel('Return horizon h (months)')
    ax.set_title('Rank IC by horizon, 2004–2026')
    ax.grid(False)
    for spine in ax.spines.values():
        spine.set_visible(False)
    bar = fig.colorbar(image, ax=ax, fraction=0.05, pad=0.03)
    bar.ax.tick_params(labelsize=7)
    bar.set_label('Mean rank IC (t in brackets)', fontsize=7.5)
    return save(fig, 'fig_horizon.pdf')


