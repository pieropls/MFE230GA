# ---------------------------------------------------------------- D6 loadings
def loadings(frame):
    """frame: rows (strategy, factor) with columns coef, se, label (CONFIRMATORY/POST-HOC)."""
    factors = ['Mkt-RF', 'SMB', 'HML', 'RMW', 'CMA', 'Mom', 'group_momentum']
    names = {'group_momentum': 'Industry mom.'}
    strategies = list(dict.fromkeys(frame.strategy))
    fig, ax = plt.subplots(figsize=(P.FULL_WIDTH, 2.7))
    width = 0.8 / len(strategies)
    shades = iter([GREY, LGREY, DGREY])
    markers = iter(['o', 'D', '^', 's', 'v'])
    for i, s in enumerate(strategies):
        sub = frame.loc[frame.strategy == s].set_index('factor').reindex(factors)
        label = sub.label.iloc[0]
        colour = C if s.startswith('A3') else PH if label == P.POSTHOC else next(shades)
        x = np.arange(len(factors)) + (i - (len(strategies) - 1) / 2) * width
        ax.errorbar(x, sub.coef, yerr=2 * sub.se, fmt=next(markers), color=colour, ms=4, capsize=2, lw=1,
                    label=s)
    ax.axhline(0, color=DGREY, lw=0.8)
    ax.set_xticks(range(len(factors)), [names.get(f, f) for f in factors])
    ax.set_ylabel('Loading (±2 s.e., Newey–West)')
    ax.set_title('Factor exposures of the long–short books')
    ax.legend(loc='upper left', ncol=len(strategies))
    ax.grid(axis='x', visible=False)
    return save(fig, 'fig_loadings.pdf')


